import { expect, test } from "@playwright/test";
import { gotoControl, showChat, activeCanvasId, controlDispatch, gotoDisplay, todoCardRecord } from "./helpers1";

test("Hark compact navigation, add menu and reading-only file policy", async ({ context }, info) => {
  await context.addInitScript(() => {
    localStorage.setItem("vivic.voice.providers.v1", JSON.stringify({ stt: "none", tts: "none", browserVoice: "" }));
    localStorage.setItem("vivic.deviceLocation.v1", "off");
    if (navigator.mediaDevices) navigator.mediaDevices.getUserMedia = async () => { throw Error("no physical media"); };
    HTMLMediaElement.prototype.play = async () => {};
  });
  const page = await gotoControl(context); await showChat(page);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.evaluate(async () => { const { getControlHost } = await import("/src/sync/browserRuntime.ts"); (await getControlHost()).setPreferences({ theme: "light" }); });
  await expect(page.getByRole("button", { name: "查询资料", exact: true })).toBeHidden();
  await expect(page.getByRole("button", { name: "上传文件", exact: true })).toBeHidden();
  await expect(page.getByRole("button", { name: "显示全部", exact: true })).toHaveCount(0);
  const input = page.locator("[data-vivic-command-input]");
  await input.fill("帮我整理明天的出行准备");
  await expect(page.locator("[data-vivic-command-send]")).toBeVisible();
  await expect(page.locator("[data-vivic-ptt]")).toBeHidden();
  await expect(page.locator(".vivic-composer")).toHaveCSS("max-width", "512px");
  await page.screenshot({ path: info.outputPath("01-chat-desktop.png") });
  await page.getByRole("button", { name: "添加内容", exact: true }).click();
  await expect(page.getByRole("button", { name: "上传文件", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "添加图片", exact: true })).toBeVisible();
  await expect(page.locator('input[aria-label="选择文件"]').first()).toHaveAttribute("accept", ".md,.pdf");
  await page.screenshot({ path: info.outputPath("02-add-menu.png") });
  await page.getByRole("button", { name: "查询资料", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "查询资料", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "关闭窗口", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "添加内容", exact: true })).toBeFocused();
  await expect(input).toHaveValue("帮我整理明天的出行准备");
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.locator(".vivic-chat-header").evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("03-chat-narrow.png") });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('[data-vivic-chat] input[aria-label="选择文件"]').setInputFiles({ name: "杭州行程.md", mimeType: "text/markdown", buffer: Buffer.from("# 杭州三日\n\n给行程留一点空白。\n\n- 湖边散步\n- 午后喝茶\n- 看一场日落") });
  await expect(page.getByText("已保存 1 张文件卡片到 Space", { exact: true })).toBeVisible();
  const id = await activeCanvasId(page);
  await controlDispatch(page, "minimal-todo", id, [{ type: "card.create", card: todoCardRecord("minimal-todo", ["核对车票与住宿", "下载离线资料", "确认同行安排"]) }]);
  const display = await gotoDisplay(context, id);
  await expect(display.getByRole("button", { name: "打开文件：杭州行程.md", exact: true })).toBeVisible();
  await display.screenshot({ path: info.outputPath("04-space.png") });
  const imported = await page.evaluate(async canvasId => {
    const [{ putFileBatch }, { getControlHost }] = await Promise.all([import("/src/files/assetStore.ts"), import("/src/sync/browserRuntime.ts")]);
    const original = new Blob(["LEGACY ORIGINAL - do not preview"]), sha256 = "a".repeat(64);
    const mediaType = "application/vnd.openxmlformats-officedocument.wordprocessingml.document";
    await putFileBatch(canvasId, [{ canvasId, fileId: "legacy-word", name: "历史文档.docx", mediaType, sizeBytes: original.size, sha256, blob: original, text: "LEGACY EXTRACT MUST NOT APPEAR", parseStatus: "ready", createdAt: new Date().toISOString() }]);
    const host = await getControlHost(); return host.dispatch({ schemaVersion: "0.6", requestId: "legacy-word-card", canvasId, actions: [{ type: "card.create", card: { id: "legacy-word", type: "FileCard", variant: "standard", sourceData: {}, sources: [], displayProps: { fileId: "legacy-word", name: "历史文档.docx", mediaType, sizeBytes: original.size, sha256, previewText: "LEGACY EXTRACT MUST NOT APPEAR", parseStatus: "ready" }, layout: { x: 20, y: 20, width: 320, height: 260, pinned: false, surface: "user" }, metadata: { createdAt: "2026-10-24T00:00:00Z", updatedAt: "2026-10-24T00:00:00Z" } } }] });
  }, id);
  expect(imported.ok).toBe(true);
  await expect(page.getByText("LEGACY EXTRACT MUST NOT APPEAR", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "打开文件：历史文档.docx", exact: true }).click();
  await expect(page.getByText("仅支持 PDF 和 Markdown 阅读。此文件可下载后查看。", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "问 Vivic", exact: true })).toHaveCount(0);
  const download = page.waitForEvent("download"); await page.getByRole("button", { name: "下载原文件", exact: true }).click();
  expect((await download).suggestedFilename()).toBe("历史文档.docx");
  expect(errors).toEqual([]);
});
